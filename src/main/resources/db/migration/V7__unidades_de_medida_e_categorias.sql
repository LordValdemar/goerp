CREATE TABLE unidade_medida (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL REFERENCES empresa (id),
    sigla          VARCHAR(6)   NOT NULL,
    descricao      VARCHAR(60)  NOT NULL,
    fracionavel    BOOLEAN      NOT NULL,
    ativa          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL,
    criado_por     BIGINT,
    atualizado_em  TIMESTAMPTZ  NOT NULL,
    atualizado_por BIGINT,
    CONSTRAINT uk_unidade_medida_sigla_por_empresa UNIQUE (empresa_id, sigla),
    CONSTRAINT ck_unidade_medida_sigla CHECK (sigla ~ '^[A-Z0-9]{1,6}$')
);

CREATE TABLE unidade_medida_aud (
    id           BIGINT   NOT NULL,
    rev          BIGINT   NOT NULL REFERENCES revisao (id),
    revtype      SMALLINT,
    empresa_id   BIGINT,
    sigla        VARCHAR(6),
    descricao    VARCHAR(60),
    fracionavel  BOOLEAN,
    ativa        BOOLEAN,
    PRIMARY KEY (id, rev)
);

CREATE TABLE categoria (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL REFERENCES empresa (id),
    nome           VARCHAR(80)  NOT NULL,
    ativa          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL,
    criado_por     BIGINT,
    atualizado_em  TIMESTAMPTZ  NOT NULL,
    atualizado_por BIGINT
);

CREATE UNIQUE INDEX uk_categoria_nome_por_empresa ON categoria (empresa_id, lower(nome));

CREATE TABLE categoria_aud (
    id          BIGINT   NOT NULL,
    rev         BIGINT   NOT NULL REFERENCES revisao (id),
    revtype     SMALLINT,
    empresa_id  BIGINT,
    nome        VARCHAR(80),
    ativa       BOOLEAN,
    PRIMARY KEY (id, rev)
);

-- Empresas cadastradas antes desta versão também recebem as unidades padrão
-- (as novas recebem pelo cadastro de empresa; mesma lista de UnidadeDeMedida.padroesDa)
INSERT INTO unidade_medida (empresa_id, sigla, descricao, fracionavel, criado_em, atualizado_em)
SELECT e.id, p.sigla, p.descricao, p.fracionavel, now(), now()
FROM empresa e
CROSS JOIN (VALUES
    ('UN', 'Unidade', FALSE), ('KG', 'Quilograma', TRUE), ('G', 'Grama', TRUE), ('L', 'Litro', TRUE),
    ('ML', 'Mililitro', TRUE), ('M', 'Metro', TRUE), ('CX', 'Caixa', FALSE), ('PC', 'Peça', FALSE),
    ('PCT', 'Pacote', FALSE), ('DZ', 'Dúzia', FALSE)
) AS p (sigla, descricao, fracionavel);
