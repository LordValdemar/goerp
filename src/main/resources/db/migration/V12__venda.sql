ALTER TABLE caixa ADD CONSTRAINT uk_caixa_id_empresa UNIQUE (id, empresa_id);

CREATE TABLE venda (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id           BIGINT         NOT NULL REFERENCES empresa (id),
    numero               BIGINT         NOT NULL,
    caixa_id             BIGINT         NOT NULL,
    operador_id          BIGINT         NOT NULL REFERENCES usuario (id),
    cliente_id           BIGINT,
    cpf_na_nota          VARCHAR(11),
    desconto_na_venda    NUMERIC(15, 2) NOT NULL,
    total                NUMERIC(15, 2) NOT NULL CHECK (total >= 0),
    troco                NUMERIC(15, 2) NOT NULL CHECK (troco >= 0),
    momento              TIMESTAMPTZ    NOT NULL,
    situacao             VARCHAR(20)    NOT NULL,
    cancelada_em         TIMESTAMPTZ,
    motivo_cancelamento  VARCHAR(300),
    cancelada_por        BIGINT,
    versao               BIGINT         NOT NULL DEFAULT 0,
    criado_em            TIMESTAMPTZ    NOT NULL,
    criado_por           BIGINT,
    atualizado_em        TIMESTAMPTZ    NOT NULL,
    atualizado_por       BIGINT,
    CONSTRAINT uk_venda_numero_por_empresa UNIQUE (empresa_id, numero),
    CONSTRAINT fk_venda_caixa_mesma_empresa FOREIGN KEY (caixa_id, empresa_id) REFERENCES caixa (id, empresa_id),
    CONSTRAINT fk_venda_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id)
);

CREATE INDEX idx_venda_caixa ON venda (caixa_id);
CREATE INDEX idx_venda_momento ON venda (empresa_id, momento);

CREATE TABLE venda_item (
    venda_id        BIGINT         NOT NULL REFERENCES venda (id),
    posicao         INTEGER        NOT NULL,
    produto_id      BIGINT         NOT NULL REFERENCES produto (id),
    codigo          VARCHAR(30)    NOT NULL,
    descricao       VARCHAR(120)   NOT NULL,
    quantidade      NUMERIC(15, 3) NOT NULL CHECK (quantidade > 0),
    preco_unitario  NUMERIC(15, 2) NOT NULL CHECK (preco_unitario >= 0),
    desconto        NUMERIC(15, 2) NOT NULL CHECK (desconto >= 0),
    PRIMARY KEY (venda_id, posicao)
);

CREATE TABLE venda_pagamento (
    venda_id  BIGINT         NOT NULL REFERENCES venda (id),
    posicao   INTEGER        NOT NULL,
    forma     VARCHAR(20)    NOT NULL,
    valor     NUMERIC(15, 2) NOT NULL CHECK (valor > 0),
    PRIMARY KEY (venda_id, posicao)
);

CREATE TABLE venda_aud (
    id                   BIGINT   NOT NULL,
    rev                  BIGINT   NOT NULL REFERENCES revisao (id),
    revtype              SMALLINT,
    empresa_id           BIGINT,
    numero               BIGINT,
    caixa_id             BIGINT,
    operador_id          BIGINT,
    cliente_id           BIGINT,
    cpf_na_nota          VARCHAR(11),
    desconto_na_venda    NUMERIC(15, 2),
    total                NUMERIC(15, 2),
    troco                NUMERIC(15, 2),
    momento              TIMESTAMPTZ,
    situacao             VARCHAR(20),
    cancelada_em         TIMESTAMPTZ,
    motivo_cancelamento  VARCHAR(300),
    cancelada_por        BIGINT,
    PRIMARY KEY (id, rev)
);

-- Contador de números de venda por empresa (incrementado atomicamente)
CREATE TABLE numeracao_venda (
    empresa_id     BIGINT PRIMARY KEY REFERENCES empresa (id),
    ultimo_numero  BIGINT NOT NULL
);

CREATE TABLE configuracao_venda (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id                  BIGINT        NOT NULL UNIQUE REFERENCES empresa (id),
    desconto_maximo_percentual  NUMERIC(5, 2) NOT NULL CHECK (desconto_maximo_percentual BETWEEN 0 AND 100),
    criado_em                   TIMESTAMPTZ   NOT NULL,
    criado_por                  BIGINT,
    atualizado_em               TIMESTAMPTZ   NOT NULL,
    atualizado_por              BIGINT
);

CREATE TABLE configuracao_venda_aud (
    id                          BIGINT   NOT NULL,
    rev                         BIGINT   NOT NULL REFERENCES revisao (id),
    revtype                     SMALLINT,
    empresa_id                  BIGINT,
    desconto_maximo_percentual  NUMERIC(5, 2),
    PRIMARY KEY (id, rev)
);
