CREATE TABLE pedido_venda (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id           BIGINT         NOT NULL REFERENCES empresa (id),
    numero               BIGINT         NOT NULL,
    cliente_id           BIGINT         NOT NULL REFERENCES cliente (id),
    vendedor_id          BIGINT         NOT NULL REFERENCES usuario (id),
    criado_no_pedido_em  TIMESTAMPTZ    NOT NULL,
    desconto             NUMERIC(15, 2) NOT NULL CHECK (desconto >= 0),
    total                NUMERIC(15, 2) NOT NULL CHECK (total >= 0),
    validade             DATE           NOT NULL,
    observacoes          VARCHAR(1000),
    situacao             VARCHAR(20)    NOT NULL,
    confirmado_em        TIMESTAMPTZ,
    faturado_em          TIMESTAMPTZ,
    cancelado_em         TIMESTAMPTZ,
    motivo_cancelamento  VARCHAR(300),
    versao               BIGINT         NOT NULL DEFAULT 0,
    criado_em            TIMESTAMPTZ    NOT NULL,
    criado_por           BIGINT,
    atualizado_em        TIMESTAMPTZ    NOT NULL,
    atualizado_por       BIGINT,
    CONSTRAINT uk_pedido_venda_numero_por_empresa UNIQUE (empresa_id, numero)
);

CREATE INDEX idx_pedido_venda_cliente ON pedido_venda (empresa_id, cliente_id);

CREATE TABLE pedido_venda_item (
    pedido_id       BIGINT         NOT NULL REFERENCES pedido_venda (id),
    posicao         INTEGER        NOT NULL,
    produto_id      BIGINT         NOT NULL REFERENCES produto (id),
    codigo          VARCHAR(30)    NOT NULL,
    descricao       VARCHAR(120)   NOT NULL,
    quantidade      NUMERIC(15, 3) NOT NULL CHECK (quantidade > 0),
    preco_unitario  NUMERIC(15, 2) NOT NULL CHECK (preco_unitario >= 0),
    desconto        NUMERIC(15, 2) NOT NULL CHECK (desconto >= 0),
    PRIMARY KEY (pedido_id, posicao)
);

CREATE TABLE pedido_venda_aud (
    id                   BIGINT   NOT NULL,
    rev                  BIGINT   NOT NULL REFERENCES revisao (id),
    revtype              SMALLINT,
    empresa_id           BIGINT,
    numero               BIGINT,
    cliente_id           BIGINT,
    vendedor_id          BIGINT,
    criado_no_pedido_em  TIMESTAMPTZ,
    desconto             NUMERIC(15, 2),
    total                NUMERIC(15, 2),
    validade             DATE,
    observacoes          VARCHAR(1000),
    situacao             VARCHAR(20),
    confirmado_em        TIMESTAMPTZ,
    faturado_em          TIMESTAMPTZ,
    cancelado_em         TIMESTAMPTZ,
    motivo_cancelamento  VARCHAR(300),
    PRIMARY KEY (id, rev)
);

-- Alterar itens gera, na mesma revisão, remoção e inclusão na mesma posição: revtype faz parte da chave
CREATE TABLE pedido_venda_item_aud (
    rev             BIGINT         NOT NULL REFERENCES revisao (id),
    revtype         SMALLINT       NOT NULL,
    pedido_id       BIGINT         NOT NULL,
    posicao         INTEGER        NOT NULL,
    produto_id      BIGINT,
    codigo          VARCHAR(30),
    descricao       VARCHAR(120),
    quantidade      NUMERIC(15, 3),
    preco_unitario  NUMERIC(15, 2),
    desconto        NUMERIC(15, 2),
    PRIMARY KEY (rev, revtype, pedido_id, posicao)
);

CREATE TABLE numeracao_pedido_venda (
    empresa_id     BIGINT PRIMARY KEY REFERENCES empresa (id),
    ultimo_numero  BIGINT NOT NULL
);
