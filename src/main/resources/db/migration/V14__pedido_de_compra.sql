ALTER TABLE fornecedor ADD CONSTRAINT uk_fornecedor_id_empresa UNIQUE (id, empresa_id);

CREATE TABLE pedido_compra (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id           BIGINT         NOT NULL REFERENCES empresa (id),
    numero               BIGINT         NOT NULL,
    fornecedor_id        BIGINT         NOT NULL,
    comprador_id         BIGINT         NOT NULL REFERENCES usuario (id),
    criado_no_pedido_em  TIMESTAMPTZ    NOT NULL,
    previsao_entrega     DATE,
    observacoes          VARCHAR(1000),
    total                NUMERIC(15, 2) NOT NULL CHECK (total >= 0),
    situacao             VARCHAR(30)    NOT NULL,
    enviado_em           TIMESTAMPTZ,
    encerrado_em         TIMESTAMPTZ,
    motivo_encerramento  VARCHAR(300),
    versao               BIGINT         NOT NULL DEFAULT 0,
    criado_em            TIMESTAMPTZ    NOT NULL,
    criado_por           BIGINT,
    atualizado_em        TIMESTAMPTZ    NOT NULL,
    atualizado_por       BIGINT,
    CONSTRAINT uk_pedido_compra_numero_por_empresa UNIQUE (empresa_id, numero),
    CONSTRAINT fk_pedido_compra_fornecedor_mesma_empresa
        FOREIGN KEY (fornecedor_id, empresa_id) REFERENCES fornecedor (id, empresa_id)
);

CREATE INDEX idx_pedido_compra_fornecedor ON pedido_compra (empresa_id, fornecedor_id);

CREATE TABLE pedido_compra_item (
    pedido_id        BIGINT         NOT NULL REFERENCES pedido_compra (id),
    posicao          INTEGER        NOT NULL,
    produto_id       BIGINT         NOT NULL REFERENCES produto (id),
    codigo           VARCHAR(30)    NOT NULL,
    descricao        VARCHAR(120)   NOT NULL,
    quantidade       NUMERIC(15, 3) NOT NULL CHECK (quantidade > 0),
    custo_negociado  NUMERIC(15, 4) NOT NULL CHECK (custo_negociado >= 0),
    recebida         NUMERIC(15, 3) NOT NULL CHECK (recebida >= 0),
    PRIMARY KEY (pedido_id, posicao),
    CONSTRAINT ck_pedido_compra_item_recebida CHECK (recebida <= quantidade)
);

CREATE TABLE pedido_compra_aud (
    id                   BIGINT   NOT NULL,
    rev                  BIGINT   NOT NULL REFERENCES revisao (id),
    revtype              SMALLINT,
    empresa_id           BIGINT,
    numero               BIGINT,
    fornecedor_id        BIGINT,
    comprador_id         BIGINT,
    criado_no_pedido_em  TIMESTAMPTZ,
    previsao_entrega     DATE,
    observacoes          VARCHAR(1000),
    total                NUMERIC(15, 2),
    situacao             VARCHAR(30),
    enviado_em           TIMESTAMPTZ,
    encerrado_em         TIMESTAMPTZ,
    motivo_encerramento  VARCHAR(300),
    PRIMARY KEY (id, rev)
);

-- Alterar ou receber itens gera, na mesma revisão, remoção e inclusão na mesma posição
CREATE TABLE pedido_compra_item_aud (
    rev              BIGINT         NOT NULL REFERENCES revisao (id),
    revtype          SMALLINT       NOT NULL,
    pedido_id        BIGINT         NOT NULL,
    posicao          INTEGER        NOT NULL,
    produto_id       BIGINT,
    codigo           VARCHAR(30),
    descricao        VARCHAR(120),
    quantidade       NUMERIC(15, 3),
    custo_negociado  NUMERIC(15, 4),
    recebida         NUMERIC(15, 3),
    PRIMARY KEY (rev, revtype, pedido_id, posicao)
);

CREATE TABLE numeracao_pedido_compra (
    empresa_id     BIGINT PRIMARY KEY REFERENCES empresa (id),
    ultimo_numero  BIGINT NOT NULL
);
