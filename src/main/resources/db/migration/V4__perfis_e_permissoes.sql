CREATE TABLE perfil (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL REFERENCES empresa (id),
    nome           VARCHAR(80)  NOT NULL,
    administrador  BOOLEAN      NOT NULL DEFAULT FALSE,
    ativo          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL,
    criado_por     BIGINT,
    atualizado_em  TIMESTAMPTZ  NOT NULL,
    atualizado_por BIGINT,
    -- permite que o vínculo referencie (perfil, empresa) e garanta que o perfil é da mesma empresa
    CONSTRAINT uk_perfil_id_empresa UNIQUE (id, empresa_id)
);

CREATE UNIQUE INDEX uk_perfil_nome_por_empresa ON perfil (empresa_id, lower(nome));

CREATE TABLE perfil_permissao (
    perfil_id  BIGINT      NOT NULL REFERENCES perfil (id),
    permissao  VARCHAR(50) NOT NULL,
    PRIMARY KEY (perfil_id, permissao)
);

CREATE TABLE perfil_aud (
    id             BIGINT   NOT NULL,
    rev            BIGINT   NOT NULL REFERENCES revisao (id),
    revtype        SMALLINT,
    empresa_id     BIGINT,
    nome           VARCHAR(80),
    administrador  BOOLEAN,
    ativo          BOOLEAN,
    PRIMARY KEY (id, rev)
);

CREATE TABLE perfil_permissao_aud (
    rev        BIGINT      NOT NULL REFERENCES revisao (id),
    revtype    SMALLINT,
    perfil_id  BIGINT      NOT NULL,
    permissao  VARCHAR(50) NOT NULL,
    PRIMARY KEY (rev, perfil_id, permissao)
);

-- Todo vínculo tem um perfil, e o perfil precisa ser da mesma empresa do vínculo
ALTER TABLE usuario_empresa
    ADD COLUMN perfil_id BIGINT NOT NULL,
    ADD CONSTRAINT fk_usuario_empresa_perfil_mesma_empresa
        FOREIGN KEY (perfil_id, empresa_id) REFERENCES perfil (id, empresa_id);

CREATE INDEX idx_usuario_empresa_perfil ON usuario_empresa (perfil_id);

ALTER TABLE usuario_empresa_aud ADD COLUMN perfil_id BIGINT;
