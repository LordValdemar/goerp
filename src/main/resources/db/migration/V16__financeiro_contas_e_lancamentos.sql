-- Plano de contas simples (receitas e despesas) de cada empresa
CREATE TABLE categoria_financeira (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL REFERENCES empresa (id),
    tipo           VARCHAR(10)  NOT NULL,
    nome           VARCHAR(80)  NOT NULL,
    ativa          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL,
    criado_por     BIGINT,
    atualizado_em  TIMESTAMPTZ  NOT NULL,
    atualizado_por BIGINT,
    CONSTRAINT uk_categoria_financeira_id_empresa UNIQUE (id, empresa_id),
    CONSTRAINT ck_categoria_financeira_tipo CHECK (tipo IN ('RECEITA', 'DESPESA'))
);

CREATE UNIQUE INDEX uk_categoria_financeira_nome ON categoria_financeira (empresa_id, lower(nome));

CREATE TABLE categoria_financeira_aud (
    id          BIGINT   NOT NULL,
    rev         BIGINT   NOT NULL REFERENCES revisao (id),
    revtype     SMALLINT,
    empresa_id  BIGINT,
    tipo        VARCHAR(10),
    nome        VARCHAR(80),
    ativa       BOOLEAN,
    PRIMARY KEY (id, rev)
);

-- Caixa, banco ou conta de pagamento. O saldo só muda junto com um lançamento, na mesma transação.
CREATE TABLE conta_financeira (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id              BIGINT         NOT NULL REFERENCES empresa (id),
    tipo                    VARCHAR(20)    NOT NULL,
    nome                    VARCHAR(80)    NOT NULL,
    permite_saldo_negativo  BOOLEAN        NOT NULL DEFAULT FALSE,
    saldo                   NUMERIC(15, 2) NOT NULL DEFAULT 0,
    ativa                   BOOLEAN        NOT NULL DEFAULT TRUE,
    versao                  BIGINT         NOT NULL DEFAULT 0,
    criado_em               TIMESTAMPTZ    NOT NULL,
    criado_por              BIGINT,
    atualizado_em           TIMESTAMPTZ    NOT NULL,
    atualizado_por          BIGINT,
    CONSTRAINT uk_conta_financeira_id_empresa UNIQUE (id, empresa_id)
);

CREATE UNIQUE INDEX uk_conta_financeira_nome ON conta_financeira (empresa_id, lower(nome));

-- O saldo não é auditado aqui: o histórico dele são os próprios lançamentos
CREATE TABLE conta_financeira_aud (
    id                      BIGINT   NOT NULL,
    rev                     BIGINT   NOT NULL REFERENCES revisao (id),
    revtype                 SMALLINT,
    empresa_id              BIGINT,
    tipo                    VARCHAR(20),
    nome                    VARCHAR(80),
    permite_saldo_negativo  BOOLEAN,
    ativa                   BOOLEAN,
    PRIMARY KEY (id, rev)
);

-- Livro de lançamentos: só recebe INSERT (correção é por estorno)
CREATE TABLE lancamento_financeiro (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id        BIGINT         NOT NULL REFERENCES empresa (id),
    conta_id          BIGINT         NOT NULL,
    tipo              VARCHAR(20)    NOT NULL,
    valor             NUMERIC(15, 2) NOT NULL,
    saldo_resultante  NUMERIC(15, 2) NOT NULL,
    forma             VARCHAR(20)    NOT NULL,
    categoria_id      BIGINT,
    descricao         VARCHAR(200)   NOT NULL,
    origem            VARCHAR(30)    NOT NULL,
    documento_origem  BIGINT,
    estornado_id      BIGINT REFERENCES lancamento_financeiro (id),
    usuario_id        BIGINT,
    momento           TIMESTAMPTZ    NOT NULL,
    CONSTRAINT fk_lancamento_conta_mesma_empresa
        FOREIGN KEY (conta_id, empresa_id) REFERENCES conta_financeira (id, empresa_id),
    CONSTRAINT fk_lancamento_categoria_mesma_empresa
        FOREIGN KEY (categoria_id, empresa_id) REFERENCES categoria_financeira (id, empresa_id),
    CONSTRAINT ck_lancamento_valor_positivo CHECK (valor > 0),
    -- a prazo gera título, nunca lançamento: nenhum dinheiro mudou de mãos
    CONSTRAINT ck_lancamento_forma_movimenta CHECK (forma <> 'A_PRAZO')
);

CREATE UNIQUE INDEX uk_lancamento_estornado ON lancamento_financeiro (estornado_id) WHERE estornado_id IS NOT NULL;
CREATE INDEX idx_lancamento_conta ON lancamento_financeiro (empresa_id, conta_id, id);
CREATE INDEX idx_lancamento_documento ON lancamento_financeiro (empresa_id, origem, documento_origem);

CREATE FUNCTION impedir_alteracao_de_lancamento() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Lançamentos financeiros não podem ser alterados nem apagados; use estorno';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_lancamento_financeiro_imutavel
    BEFORE UPDATE OR DELETE ON lancamento_financeiro
    FOR EACH ROW EXECUTE FUNCTION impedir_alteracao_de_lancamento();

-- Número que liga as duas pontas de uma transferência
CREATE TABLE numeracao_transferencia_financeira (
    empresa_id     BIGINT PRIMARY KEY REFERENCES empresa (id),
    ultimo_numero  BIGINT NOT NULL
);
