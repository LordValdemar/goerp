CREATE TABLE cliente (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id             BIGINT        NOT NULL REFERENCES empresa (id),
    documento              VARCHAR(14)   NOT NULL,
    nome                   VARCHAR(150)  NOT NULL,
    nome_fantasia          VARCHAR(150),
    inscricao_estadual     VARCHAR(20),
    indicador_ie           VARCHAR(20)   NOT NULL,
    email                  VARCHAR(150),
    telefone               VARCHAR(11),
    cep                    VARCHAR(8),
    logradouro             VARCHAR(150),
    numero                 VARCHAR(20),
    complemento            VARCHAR(100),
    bairro                 VARCHAR(100),
    municipio              VARCHAR(100),
    codigo_ibge_municipio  VARCHAR(7),
    uf                     VARCHAR(2),
    limite_credito         NUMERIC(15, 2),
    observacoes            VARCHAR(1000),
    ativo                  BOOLEAN       NOT NULL DEFAULT TRUE,
    versao                 BIGINT        NOT NULL DEFAULT 0,
    criado_em              TIMESTAMPTZ   NOT NULL,
    criado_por             BIGINT,
    atualizado_em          TIMESTAMPTZ   NOT NULL,
    atualizado_por         BIGINT,
    CONSTRAINT uk_cliente_documento_por_empresa UNIQUE (empresa_id, documento),
    CONSTRAINT ck_cliente_limite_nao_negativo CHECK (limite_credito IS NULL OR limite_credito >= 0)
);

CREATE INDEX idx_cliente_nome ON cliente (empresa_id, lower(nome));

CREATE TABLE cliente_aud (
    id                     BIGINT   NOT NULL,
    rev                    BIGINT   NOT NULL REFERENCES revisao (id),
    revtype                SMALLINT,
    empresa_id             BIGINT,
    documento              VARCHAR(14),
    nome                   VARCHAR(150),
    nome_fantasia          VARCHAR(150),
    inscricao_estadual     VARCHAR(20),
    indicador_ie           VARCHAR(20),
    email                  VARCHAR(150),
    telefone               VARCHAR(11),
    cep                    VARCHAR(8),
    logradouro             VARCHAR(150),
    numero                 VARCHAR(20),
    complemento            VARCHAR(100),
    bairro                 VARCHAR(100),
    municipio              VARCHAR(100),
    codigo_ibge_municipio  VARCHAR(7),
    uf                     VARCHAR(2),
    limite_credito         NUMERIC(15, 2),
    observacoes            VARCHAR(1000),
    ativo                  BOOLEAN,
    PRIMARY KEY (id, rev)
);
