CREATE TABLE usuario (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                      VARCHAR(150) NOT NULL,
    email                     VARCHAR(150) NOT NULL UNIQUE,
    senha_hash                VARCHAR(100) NOT NULL,
    administrador_plataforma  BOOLEAN      NOT NULL DEFAULT FALSE,
    ativo                     BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em                 TIMESTAMPTZ  NOT NULL,
    criado_por                BIGINT,
    atualizado_em             TIMESTAMPTZ  NOT NULL,
    atualizado_por            BIGINT
);

CREATE TABLE usuario_aud (
    id                        BIGINT   NOT NULL,
    rev                       BIGINT   NOT NULL REFERENCES revisao (id),
    revtype                   SMALLINT,
    nome                      VARCHAR(150),
    email                     VARCHAR(150),
    administrador_plataforma  BOOLEAN,
    ativo                     BOOLEAN,
    PRIMARY KEY (id, rev)
);

-- Acesso de um usuário a uma empresa
CREATE TABLE usuario_empresa (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT      NOT NULL REFERENCES usuario (id),
    empresa_id     BIGINT      NOT NULL REFERENCES empresa (id),
    ativo          BOOLEAN     NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ NOT NULL,
    criado_por     BIGINT,
    atualizado_em  TIMESTAMPTZ NOT NULL,
    atualizado_por BIGINT,
    CONSTRAINT uk_usuario_empresa UNIQUE (usuario_id, empresa_id)
);

CREATE INDEX idx_usuario_empresa_empresa ON usuario_empresa (empresa_id);

CREATE TABLE usuario_empresa_aud (
    id          BIGINT   NOT NULL,
    rev         BIGINT   NOT NULL REFERENCES revisao (id),
    revtype     SMALLINT,
    usuario_id  BIGINT,
    empresa_id  BIGINT,
    ativo       BOOLEAN,
    PRIMARY KEY (id, rev)
);
