-- Permite referenciar (produto, empresa): o banco garante que o estoque é do produto da mesma empresa
ALTER TABLE produto ADD CONSTRAINT uk_produto_id_empresa UNIQUE (id, empresa_id);

-- Saldo atual por produto: alterado só junto com uma movimentação, na mesma transação
CREATE TABLE saldo_estoque (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT         NOT NULL REFERENCES empresa (id),
    produto_id     BIGINT         NOT NULL,
    quantidade     NUMERIC(15, 3) NOT NULL,
    custo_medio    NUMERIC(15, 4) NOT NULL,
    criado_em      TIMESTAMPTZ    NOT NULL,
    criado_por     BIGINT,
    atualizado_em  TIMESTAMPTZ    NOT NULL,
    atualizado_por BIGINT,
    CONSTRAINT uk_saldo_estoque_produto UNIQUE (empresa_id, produto_id),
    CONSTRAINT fk_saldo_estoque_produto_mesma_empresa
        FOREIGN KEY (produto_id, empresa_id) REFERENCES produto (id, empresa_id),
    CONSTRAINT ck_saldo_custo_nao_negativo CHECK (custo_medio >= 0)
);

-- Livro de movimentações: só recebe INSERT (a aplicação nunca altera nem apaga)
CREATE TABLE movimentacao_estoque (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id              BIGINT         NOT NULL REFERENCES empresa (id),
    produto_id              BIGINT         NOT NULL,
    tipo                    VARCHAR(30)    NOT NULL,
    quantidade              NUMERIC(15, 3) NOT NULL,
    custo_unitario          NUMERIC(15, 4) NOT NULL,
    saldo_resultante        NUMERIC(15, 3) NOT NULL,
    custo_medio_resultante  NUMERIC(15, 4) NOT NULL,
    origem                  VARCHAR(20)    NOT NULL,
    documento_origem        BIGINT,
    motivo                  VARCHAR(500),
    estornada_id            BIGINT REFERENCES movimentacao_estoque (id),
    usuario_id              BIGINT,
    momento                 TIMESTAMPTZ    NOT NULL,
    CONSTRAINT fk_movimentacao_produto_mesma_empresa
        FOREIGN KEY (produto_id, empresa_id) REFERENCES produto (id, empresa_id),
    CONSTRAINT ck_movimentacao_quantidade_positiva CHECK (quantidade > 0),
    CONSTRAINT ck_movimentacao_custo_nao_negativo CHECK (custo_unitario >= 0)
);

-- Cada movimentação só pode ser estornada uma vez (garantido também pelo banco)
CREATE UNIQUE INDEX uk_movimentacao_estornada ON movimentacao_estoque (estornada_id) WHERE estornada_id IS NOT NULL;
CREATE INDEX idx_movimentacao_produto ON movimentacao_estoque (empresa_id, produto_id, id);

-- Impede alteração e exclusão do livro de movimentações, mesmo por SQL direto
CREATE FUNCTION impedir_alteracao_de_movimentacao() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Movimentações de estoque não podem ser alteradas nem apagadas; use estorno';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_movimentacao_estoque_imutavel
    BEFORE UPDATE OR DELETE ON movimentacao_estoque
    FOR EACH ROW EXECUTE FUNCTION impedir_alteracao_de_movimentacao();

CREATE TABLE configuracao_estoque (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id                BIGINT      NOT NULL UNIQUE REFERENCES empresa (id),
    permite_estoque_negativo  BOOLEAN     NOT NULL DEFAULT FALSE,
    criado_em                 TIMESTAMPTZ NOT NULL,
    criado_por                BIGINT,
    atualizado_em             TIMESTAMPTZ NOT NULL,
    atualizado_por            BIGINT
);

CREATE TABLE configuracao_estoque_aud (
    id                        BIGINT   NOT NULL,
    rev                       BIGINT   NOT NULL REFERENCES revisao (id),
    revtype                   SMALLINT,
    empresa_id                BIGINT,
    permite_estoque_negativo  BOOLEAN,
    PRIMARY KEY (id, rev)
);
