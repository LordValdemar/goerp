-- Permitem referenciar (id, empresa_id) e garantir que unidade e categoria são da mesma empresa do produto
ALTER TABLE unidade_medida ADD CONSTRAINT uk_unidade_medida_id_empresa UNIQUE (id, empresa_id);
ALTER TABLE categoria ADD CONSTRAINT uk_categoria_id_empresa UNIQUE (id, empresa_id);

CREATE TABLE produto (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id       BIGINT         NOT NULL REFERENCES empresa (id),
    codigo           VARCHAR(30)    NOT NULL,
    codigo_barras    VARCHAR(14),
    descricao        VARCHAR(120)   NOT NULL,
    categoria_id     BIGINT,
    unidade_id       BIGINT         NOT NULL,
    preco_venda      NUMERIC(15, 2) NOT NULL,
    preco_custo      NUMERIC(15, 4) NOT NULL DEFAULT 0,
    ncm              VARCHAR(8)     NOT NULL,
    cest             VARCHAR(7),
    origem           VARCHAR(50)    NOT NULL,
    controla_estoque BOOLEAN        NOT NULL,
    estoque_minimo   NUMERIC(15, 3) NOT NULL DEFAULT 0,
    ativo            BOOLEAN        NOT NULL DEFAULT TRUE,
    versao           BIGINT         NOT NULL DEFAULT 0,
    criado_em        TIMESTAMPTZ    NOT NULL,
    criado_por       BIGINT,
    atualizado_em    TIMESTAMPTZ    NOT NULL,
    atualizado_por   BIGINT,
    CONSTRAINT uk_produto_codigo_por_empresa UNIQUE (empresa_id, codigo),
    CONSTRAINT fk_produto_unidade_mesma_empresa
        FOREIGN KEY (unidade_id, empresa_id) REFERENCES unidade_medida (id, empresa_id),
    CONSTRAINT fk_produto_categoria_mesma_empresa
        FOREIGN KEY (categoria_id, empresa_id) REFERENCES categoria (id, empresa_id),
    CONSTRAINT ck_produto_valores_nao_negativos
        CHECK (preco_venda >= 0 AND preco_custo >= 0 AND estoque_minimo >= 0)
);

-- Código de barras único na empresa (quando informado): é a chave da busca no PDV
CREATE UNIQUE INDEX uk_produto_codigo_barras_por_empresa ON produto (empresa_id, codigo_barras)
    WHERE codigo_barras IS NOT NULL;
CREATE INDEX idx_produto_descricao ON produto (empresa_id, lower(descricao));
CREATE INDEX idx_produto_categoria ON produto (empresa_id, categoria_id);

CREATE TABLE produto_aud (
    id               BIGINT   NOT NULL,
    rev              BIGINT   NOT NULL REFERENCES revisao (id),
    revtype          SMALLINT,
    empresa_id       BIGINT,
    codigo           VARCHAR(30),
    codigo_barras    VARCHAR(14),
    descricao        VARCHAR(120),
    categoria_id     BIGINT,
    unidade_id       BIGINT,
    preco_venda      NUMERIC(15, 2),
    preco_custo      NUMERIC(15, 4),
    ncm              VARCHAR(8),
    cest             VARCHAR(7),
    origem           VARCHAR(50),
    controla_estoque BOOLEAN,
    estoque_minimo   NUMERIC(15, 3),
    ativo            BOOLEAN,
    PRIMARY KEY (id, rev)
);
