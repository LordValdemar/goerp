CREATE TABLE caixa (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT         NOT NULL REFERENCES empresa (id),
    operador_id    BIGINT         NOT NULL REFERENCES usuario (id),
    troco_inicial  NUMERIC(15, 2) NOT NULL CHECK (troco_inicial >= 0),
    aberto_em      TIMESTAMPTZ    NOT NULL,
    situacao       VARCHAR(20)    NOT NULL,
    fechado_em     TIMESTAMPTZ,
    fechado_por    BIGINT,
    versao         BIGINT         NOT NULL DEFAULT 0,
    criado_em      TIMESTAMPTZ    NOT NULL,
    criado_por     BIGINT,
    atualizado_em  TIMESTAMPTZ    NOT NULL,
    atualizado_por BIGINT
);

-- Cada operador tem no máximo um caixa aberto por empresa (garantido também pelo banco)
CREATE UNIQUE INDEX uk_caixa_aberto_por_operador ON caixa (empresa_id, operador_id) WHERE situacao = 'ABERTO';

CREATE TABLE caixa_movimento (
    caixa_id    BIGINT         NOT NULL REFERENCES caixa (id),
    posicao     INTEGER        NOT NULL,
    tipo        VARCHAR(20)    NOT NULL,
    valor       NUMERIC(15, 2) NOT NULL CHECK (valor > 0),
    motivo      VARCHAR(300),
    usuario_id  BIGINT,
    momento     TIMESTAMPTZ    NOT NULL,
    PRIMARY KEY (caixa_id, posicao)
);

CREATE TABLE caixa_conferencia (
    caixa_id  BIGINT         NOT NULL REFERENCES caixa (id),
    posicao   INTEGER        NOT NULL,
    forma     VARCHAR(20)    NOT NULL,
    esperado  NUMERIC(15, 2) NOT NULL,
    contado   NUMERIC(15, 2) NOT NULL,
    PRIMARY KEY (caixa_id, posicao)
);

CREATE TABLE caixa_aud (
    id             BIGINT   NOT NULL,
    rev            BIGINT   NOT NULL REFERENCES revisao (id),
    revtype        SMALLINT,
    empresa_id     BIGINT,
    operador_id    BIGINT,
    troco_inicial  NUMERIC(15, 2),
    aberto_em      TIMESTAMPTZ,
    situacao       VARCHAR(20),
    fechado_em     TIMESTAMPTZ,
    fechado_por    BIGINT,
    PRIMARY KEY (id, rev)
);
