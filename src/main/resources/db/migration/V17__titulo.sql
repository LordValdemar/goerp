-- Uma parcela de conta a pagar (fornecedor opcional) ou a receber (cliente obrigatório)
CREATE TABLE titulo (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id           BIGINT         NOT NULL REFERENCES empresa (id),
    natureza             VARCHAR(10)    NOT NULL,
    fornecedor_id        BIGINT,
    cliente_id           BIGINT,
    descricao            VARCHAR(150)   NOT NULL,
    categoria_id         BIGINT,
    documento            VARCHAR(60),
    forma_prevista       VARCHAR(20)    NOT NULL,
    origem               VARCHAR(30)    NOT NULL,
    documento_origem     BIGINT,
    parcela              INTEGER        NOT NULL,
    parcelas             INTEGER        NOT NULL,
    valor                NUMERIC(15, 2) NOT NULL,
    -- guardado para consultas e totais por vencimento direto no banco; recalculado a cada pagamento
    saldo_devedor        NUMERIC(15, 2) NOT NULL,
    vencimento           DATE           NOT NULL,
    situacao             VARCHAR(20)    NOT NULL,
    motivo_cancelamento  VARCHAR(300),
    cancelado_em         TIMESTAMPTZ,
    versao               BIGINT         NOT NULL DEFAULT 0,
    criado_em            TIMESTAMPTZ    NOT NULL,
    criado_por           BIGINT,
    atualizado_em        TIMESTAMPTZ    NOT NULL,
    atualizado_por       BIGINT,
    CONSTRAINT uk_titulo_id_empresa UNIQUE (id, empresa_id),
    CONSTRAINT fk_titulo_fornecedor_mesma_empresa
        FOREIGN KEY (fornecedor_id, empresa_id) REFERENCES fornecedor (id, empresa_id),
    CONSTRAINT fk_titulo_cliente_mesma_empresa
        FOREIGN KEY (cliente_id, empresa_id) REFERENCES cliente (id, empresa_id),
    CONSTRAINT fk_titulo_categoria_mesma_empresa
        FOREIGN KEY (categoria_id, empresa_id) REFERENCES categoria_financeira (id, empresa_id),
    CONSTRAINT ck_titulo_pessoa CHECK (
        (natureza = 'A_PAGAR' AND cliente_id IS NULL)
        OR (natureza = 'A_RECEBER' AND cliente_id IS NOT NULL AND fornecedor_id IS NULL)),
    CONSTRAINT ck_titulo_valor CHECK (valor > 0 AND saldo_devedor >= 0 AND saldo_devedor <= valor),
    CONSTRAINT ck_titulo_parcela CHECK (parcela >= 1 AND parcela <= parcelas)
);

CREATE INDEX idx_titulo_vencimento ON titulo (empresa_id, natureza, situacao, vencimento);
CREATE INDEX idx_titulo_origem ON titulo (empresa_id, origem, documento_origem);

CREATE TABLE titulo_aud (
    id                   BIGINT   NOT NULL,
    rev                  BIGINT   NOT NULL REFERENCES revisao (id),
    revtype              SMALLINT,
    empresa_id           BIGINT,
    natureza             VARCHAR(10),
    fornecedor_id        BIGINT,
    cliente_id           BIGINT,
    descricao            VARCHAR(150),
    categoria_id         BIGINT,
    documento            VARCHAR(60),
    forma_prevista       VARCHAR(20),
    origem               VARCHAR(30),
    documento_origem     BIGINT,
    parcela              INTEGER,
    parcelas             INTEGER,
    valor                NUMERIC(15, 2),
    saldo_devedor        NUMERIC(15, 2),
    vencimento           DATE,
    situacao             VARCHAR(20),
    motivo_cancelamento  VARCHAR(300),
    cancelado_em         TIMESTAMPTZ,
    PRIMARY KEY (id, rev)
);

-- Cada pagamento de um título. Não é apagado: o estorno o marca.
CREATE TABLE baixa_titulo (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id        BIGINT         NOT NULL REFERENCES empresa (id),
    titulo_id         BIGINT         NOT NULL,
    numero            INTEGER        NOT NULL,
    conta_id          BIGINT         NOT NULL,
    forma             VARCHAR(20)    NOT NULL,
    valor_pago        NUMERIC(15, 2) NOT NULL,
    juros             NUMERIC(15, 2) NOT NULL,
    multa             NUMERIC(15, 2) NOT NULL,
    desconto          NUMERIC(15, 2) NOT NULL,
    usuario_id        BIGINT,
    momento           TIMESTAMPTZ    NOT NULL,
    estornada         BOOLEAN        NOT NULL DEFAULT FALSE,
    motivo_estorno    VARCHAR(200),
    estornada_em      TIMESTAMPTZ,
    criado_em         TIMESTAMPTZ    NOT NULL,
    criado_por        BIGINT,
    atualizado_em     TIMESTAMPTZ    NOT NULL,
    atualizado_por    BIGINT,
    CONSTRAINT uk_baixa_numero UNIQUE (titulo_id, numero),
    CONSTRAINT fk_baixa_titulo_mesma_empresa
        FOREIGN KEY (titulo_id, empresa_id) REFERENCES titulo (id, empresa_id),
    CONSTRAINT fk_baixa_conta_mesma_empresa
        FOREIGN KEY (conta_id, empresa_id) REFERENCES conta_financeira (id, empresa_id),
    CONSTRAINT ck_baixa_valores CHECK (valor_pago > 0 AND juros >= 0 AND multa >= 0 AND desconto >= 0),
    CONSTRAINT ck_baixa_forma_movimenta CHECK (forma <> 'A_PRAZO')
);

CREATE TABLE baixa_titulo_aud (
    id              BIGINT   NOT NULL,
    rev             BIGINT   NOT NULL REFERENCES revisao (id),
    revtype         SMALLINT,
    empresa_id      BIGINT,
    titulo_id       BIGINT,
    numero          INTEGER,
    conta_id        BIGINT,
    forma           VARCHAR(20),
    valor_pago      NUMERIC(15, 2),
    juros           NUMERIC(15, 2),
    multa           NUMERIC(15, 2),
    desconto        NUMERIC(15, 2),
    usuario_id      BIGINT,
    momento         TIMESTAMPTZ,
    estornada       BOOLEAN,
    motivo_estorno  VARCHAR(200),
    estornada_em    TIMESTAMPTZ,
    PRIMARY KEY (id, rev)
);
