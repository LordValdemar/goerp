ALTER TABLE pedido_compra ADD CONSTRAINT uk_pedido_compra_id_empresa UNIQUE (id, empresa_id);

CREATE TABLE recebimento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id      BIGINT         NOT NULL REFERENCES empresa (id),
    pedido_id       BIGINT         NOT NULL,
    nota_fiscal     VARCHAR(60)    NOT NULL,
    valor_total     NUMERIC(15, 2) NOT NULL CHECK (valor_total >= 0),
    recebido_por    BIGINT         NOT NULL REFERENCES usuario (id),
    recebido_em     TIMESTAMPTZ    NOT NULL,
    estornado       BOOLEAN        NOT NULL DEFAULT FALSE,
    estornado_em    TIMESTAMPTZ,
    motivo_estorno  VARCHAR(300),
    criado_em       TIMESTAMPTZ    NOT NULL,
    criado_por      BIGINT,
    atualizado_em   TIMESTAMPTZ    NOT NULL,
    atualizado_por  BIGINT,
    CONSTRAINT fk_recebimento_pedido_mesma_empresa
        FOREIGN KEY (pedido_id, empresa_id) REFERENCES pedido_compra (id, empresa_id)
);

CREATE INDEX idx_recebimento_pedido ON recebimento (pedido_id);
CREATE INDEX idx_recebimento_data ON recebimento (empresa_id, recebido_em);

CREATE TABLE recebimento_item (
    recebimento_id  BIGINT         NOT NULL REFERENCES recebimento (id),
    posicao         INTEGER        NOT NULL,
    produto_id      BIGINT         NOT NULL REFERENCES produto (id),
    quantidade      NUMERIC(15, 3) NOT NULL CHECK (quantidade > 0),
    custo_unitario  NUMERIC(15, 4) NOT NULL CHECK (custo_unitario >= 0),
    PRIMARY KEY (recebimento_id, posicao)
);

CREATE TABLE recebimento_aud (
    id              BIGINT   NOT NULL,
    rev             BIGINT   NOT NULL REFERENCES revisao (id),
    revtype         SMALLINT,
    empresa_id      BIGINT,
    pedido_id       BIGINT,
    nota_fiscal     VARCHAR(60),
    valor_total     NUMERIC(15, 2),
    recebido_por    BIGINT,
    recebido_em     TIMESTAMPTZ,
    estornado       BOOLEAN,
    estornado_em    TIMESTAMPTZ,
    motivo_estorno  VARCHAR(300),
    PRIMARY KEY (id, rev)
);
