-- Uma sessão por login; guarda só o hash do token de renovação
CREATE TABLE sessao_acesso (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT      NOT NULL REFERENCES usuario (id),
    empresa_id     BIGINT      REFERENCES empresa (id),
    hash_token     VARCHAR(64) NOT NULL UNIQUE,
    expira_em      TIMESTAMPTZ NOT NULL,
    revogada_em    TIMESTAMPTZ,
    criado_em      TIMESTAMPTZ NOT NULL,
    criado_por     BIGINT,
    atualizado_em  TIMESTAMPTZ NOT NULL,
    atualizado_por BIGINT
);

CREATE INDEX idx_sessao_acesso_usuario_ativa ON sessao_acesso (usuario_id) WHERE revogada_em IS NULL;

-- Trilha de segurança: login, falha, bloqueio, renovação, logout
CREATE TABLE evento_seguranca (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo             VARCHAR(30)  NOT NULL,
    email_informado  VARCHAR(150),
    usuario_id       BIGINT,
    empresa_id       BIGINT,
    ip               VARCHAR(45),
    momento          TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_evento_seguranca_usuario ON evento_seguranca (usuario_id, momento);
