CREATE TABLE inventario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT       NOT NULL REFERENCES empresa (id),
    descricao      VARCHAR(150) NOT NULL,
    aberto_em      TIMESTAMPTZ  NOT NULL,
    situacao       VARCHAR(20)  NOT NULL,
    encerrado_em   TIMESTAMPTZ,
    versao         BIGINT       NOT NULL DEFAULT 0,
    criado_em      TIMESTAMPTZ  NOT NULL,
    criado_por     BIGINT,
    atualizado_em  TIMESTAMPTZ  NOT NULL,
    atualizado_por BIGINT
);

-- No máximo um inventário aberto por empresa (garantido também pelo banco)
CREATE UNIQUE INDEX uk_inventario_aberto_por_empresa ON inventario (empresa_id) WHERE situacao = 'ABERTO';

CREATE TABLE inventario_contagem (
    inventario_id       BIGINT         NOT NULL REFERENCES inventario (id),
    posicao             INTEGER        NOT NULL,
    produto_id          BIGINT         NOT NULL REFERENCES produto (id),
    quantidade_contada  NUMERIC(15, 3) NOT NULL CHECK (quantidade_contada >= 0),
    PRIMARY KEY (inventario_id, posicao)
);

CREATE TABLE inventario_aud (
    id            BIGINT   NOT NULL,
    rev           BIGINT   NOT NULL REFERENCES revisao (id),
    revtype       SMALLINT,
    empresa_id    BIGINT,
    descricao     VARCHAR(150),
    aberto_em     TIMESTAMPTZ,
    situacao      VARCHAR(20),
    encerrado_em  TIMESTAMPTZ,
    PRIMARY KEY (id, rev)
);

CREATE TABLE inventario_contagem_aud (
    rev                 BIGINT         NOT NULL REFERENCES revisao (id),
    revtype             SMALLINT       NOT NULL,
    inventario_id       BIGINT         NOT NULL,
    posicao             INTEGER        NOT NULL,
    produto_id          BIGINT,
    quantidade_contada  NUMERIC(15, 3),
    -- uma recontagem gera, na mesma revisão, a remoção do valor antigo e a inclusão do novo na mesma posição
    PRIMARY KEY (rev, revtype, inventario_id, posicao)
);
